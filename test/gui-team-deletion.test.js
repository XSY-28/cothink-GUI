test("right-clicking a Team avatar deletes only the confirmed Team with its conversations and keeps project files", async t => {
  const f = await fixture(t);
  saveConfig(f.home, createTeamConfig({formatVersion:2,...f.models}, "UI fixture", teamId));
  const {createGuiController} = await load("src/gui-controller.js");
  const controller = await createGuiController({home:f.home,suggestedProject:null});
  const host = await startGuiServer({controller,open:false});
  t.after(()=>host.close());
  const target = await fixtureWorkspace(t,controller,{name:"待删除项目"});
  const room = await fixtureConversation(t,controller,{workspace:target});
  await controller.action("session.name",{sessionId:room.id,title:"移除的讨论"});
  const archived = await fixtureConversation(t,controller,{workspace:target});
  await controller.action("session.archive",{sessionId:archived.id,expectedRevision:archived.navigation.revision,archived:true});
  const keep = await fixtureWorkspace(t,controller,{name:"继续工作"});
  await fixtureConversation(t,controller,{workspace:keep});
  const file = join(target.project,"项目笔记.txt");
  writeFileSync(file,"需要保留");
  const browser = await chromium.launch();
  t.after(()=>browser.close());
  const page = await browser.newPage({viewport:{width:1280,height:880}});
  page.setDefaultTimeout(6000);
  await page.goto(host.url);
  const avatar = railButton(page,target.name), other = railButton(page,keep.name);
  await other.click();
  const openMenu = () => avatar.locator("[data-team-avatar-trigger]").click({button:"right"});
  const remove = page.getByRole("menuitem",{name:"删除 Team"});
  const confirm = page.getByRole("dialog",{name:"删除 Team"});
  await openMenu();
  await remove.click();
  assert.match(await confirm.innerText(), /待删除项目/);
  await confirm.getByRole("button",{name:"取消",exact:true}).click();
  assert.equal(await avatar.isVisible(),true);
  assert.equal(await other.getAttribute("aria-current"),"page");
  await avatar.focus();
  await page.keyboard.press("Shift+F10");
  await remove.waitFor();
  await page.keyboard.press("Escape");
  await remove.waitFor({state:"hidden"});
  await openMenu();
  await remove.click();
  await confirm.getByRole("button",{name:"确认删除"}).click();
  await avatar.waitFor({state:"detached"});
  assert.equal(await other.getAttribute("aria-current"),"page");
  await page.reload();
  await other.waitFor();
  assert.equal(await avatar.count(),0);
  const history = await controller.sessions({archived:"all"});
  assert.ok(!history.items.some(row=>row.id===room.id));
  assert.ok(!history.workspaces.some(row=>row.id===target.id));
  assert.equal((await controller.sessions({query:"移除的讨论",archived:"all"})).items.length,0);
  for (const id of [room.id,archived.id]) {
    assert.ok(!history.items.some(row=>row.id===id));
    await assert.rejects(controller.session(id),/不存在|已删除/);
  }
  await other.click({button:"right"});
  await remove.click();
  await confirm.getByRole("button",{name:"确认删除"}).click();
  await other.waitFor({state:"detached"});
  assert.deepEqual((await controller.sessions({archived:"all"})).workspaces,[]);
  assert.equal(readFileSync(file,"utf8"),"需要保留");
  assert.equal(f.calls.length,0);
});

test("Team deletion waits for a running conversation and removes its task from history once settled", async t => {
  let resume;
  const paused = new Promise(resolve=>{resume=resolve;});
  const f = await host(t,true,async()=>{await paused;return {text:"已结束"};});
  const {createApi} = await import("../gui/src/api.js");
  const api = createApi(f.h.token,(path,options)=>fetch(f.origin+path,options));
  const workspace = await fixtureWorkspace(t,f);
  const room = await fixtureConversation(t,f,{workspace});
  const accepted = await f.action("task.submit",await prepareSubmit(f,{sessionId:room.id,input:"等待后结束"}));
  const remove = () => api.action("workspace.delete",{workspaceId:workspace.id,expectedRevision:workspace.revision});
  try {
    await assert.rejects(remove(),e=>e.code==="WORKSPACE_CONFLICT");
    assert.ok((await api.read("bootstrap")).workspaces.some(row=>row.id===workspace.id));
  } finally { resume(); }
  assert.equal((await completed(f,accepted.taskId)).status,"completed");
  await remove();
  await assert.rejects(api.read("task",{id:accepted.taskId}),e=>e.code==="WORKSPACE_DELETED");
  const {execFileSync,spawnSync} = await import("node:child_process");
  const {fileURLToPath} = await import("node:url");
  const cli = fileURLToPath(new URL("../bin/cothink.js",import.meta.url));
  const env = {...process.env,COTHINK_HOME:f.home,PI_OFFLINE:"1"};
  const history = JSON.parse(execFileSync(process.execPath,[cli,"history","--json"],{env}));
  assert.ok(!history.some(task=>task.id===accepted.taskId));
  const shown = spawnSync(process.execPath,[cli,"show",accepted.taskId],{env,encoding:"utf8"});
  assert.notEqual(shown.status,0);
  assert.match(shown.stderr,/已删除/);
});
