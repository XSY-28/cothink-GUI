import test from "node:test";
import assert from "node:assert/strict";
import {chromium} from "playwright";
import {fixture} from "./helpers/pi-fixture.js";
import {fixtureConversation, load, submitDraft} from "./helpers/gui-controller-fixture.js";
import {complete, controller} from "./unified-gui.fixture.js";

const {startGuiServer}=await load("src/gui-server.js");

test("saved replies open the selected HTML or SVG in the reader and keep the chat draft",async t=>{
  const html='<button>开始</button><script>document.querySelector("button").onclick=e=>e.target.textContent="已开始"</script>';
  const svg='<svg viewBox="0 0 100 100"><circle cx="50" cy="50" r="40"/></svg>';
  const reply=["```HTML",html,"```","","```",svg,"```","","```js","const x = 1","```"].join("\n");
  const f=await fixture(t,()=>({text:reply}));
  const c=await controller(t,f);
  const session=await fixtureConversation(t,c);
  const turn=await submitDraft(c,{sessionId:session.id,input:"两个内嵌页面示例"});
  await complete(c,turn.taskId);
  const host=await startGuiServer({controller:c,open:false});
  t.after(()=>host.close());
  const browser=await chromium.launch();
  t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1280,height:880}});
  page.setDefaultTimeout(5000);
  await page.addInitScript(id=>sessionStorage.setItem("cothink.session",id),session.id);
  await page.goto(host.url);
  const editor=page.getByLabel("输入问题",{exact:true});
  await editor.fill("继续修改颜色");
  const buttons=page.getByRole("button",{name:"预览",exact:true});
  await buttons.first().waitFor();
  assert.equal(await buttons.count(),2);
  assert.equal(page.frames().length,1);
  const preview=buttons.first();
  assert.equal(await preview.innerText(),"");
  await page.getByRole("button",{name:/展开代码.*html/i}).focus();
  await page.keyboard.press("Tab");
  assert.equal(await preview.evaluate(el=>document.activeElement===el),true);
  await preview.locator("..").getByText("预览",{exact:true}).waitFor();
  const loaded=page.waitForResponse(response=>response.url()===host.origin+"/reply-preview.html");
  await preview.press("Enter");
  const response=await loaded;
  assert.match(response.headers()["content-security-policy"],/default-src 'none'/);
  const panel=page.getByRole("complementary",{name:"阅读面板"});
  const frame=panel.frameLocator('iframe[title="网页预览"]');
  await frame.getByRole("button",{name:"开始"}).click();
  await frame.getByRole("button",{name:"已开始"}).waitFor();
  assert.equal(await frame.locator("body").evaluate(el=>el.ownerDocument.defaultView.origin),"null");
  const chatHeader=await page.locator("main > header").boundingBox();
  const panelBox=await panel.boundingBox();
  assert.equal(panelBox.x,chatHeader.x+chatHeader.width,"docked columns share one edge");
  assert.deepEqual(await panel.evaluate(el=>{
    const style=getComputedStyle(el);
    return [style.borderTopLeftRadius,style.borderBottomLeftRadius];
  }),["0px","0px"]);
  assert.equal((await panel.locator("iframe").boundingBox()).y,chatHeader.y+chatHeader.height,"header baselines align");
  assert.equal(await page.locator("article pre").first().isVisible(),false);
  await buttons.nth(1).click();
  await frame.locator("svg circle").waitFor();
  assert.equal(await frame.getByRole("button").count(),0);
  const close=panel.getByRole("button",{name:"关闭预览"});
  assert.equal(await close.innerText(),"");
  await close.hover();
  await close.locator("..").getByText("关闭预览",{exact:true}).waitFor();
  await close.click();
  await panel.waitFor({state:"detached"});
  assert.equal(await editor.inputValue(),"继续修改颜色");
  assert.equal(page.frames().length,1);
  assert.equal(f.calls.length,1);
});
